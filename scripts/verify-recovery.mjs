import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createApp } from '../server.mjs';
import { Vision } from '../lib/vision.mjs';
import { browserTools } from './browser.mjs';

// An isolated service and browser profile: no account, installation, or model calls.
const html = await readFile(new URL('../public/demo.html',import.meta.url),'utf8');
const observation = { summary:'A task board',readable:true,observations:[{ label:'Board',detail:'Three task columns',box:[0,0,1,1] }] };
const vision = new Vision({ status:async()=>({ configured:true,cli:true,model:'gpt-6-astra' }),inference:async()=>({ model:'gpt-6-astra',result:{ title:'Verified board',reply:'Task board ready.',changes:['Working tasks'],html,observation } }) });
const server = createApp({ vision,login:async()=>({configured:true}) });
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const { chromium } = browserTools();
const browser = await chromium.launch({ channel:'chrome',headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream'] });
const page = await browser.newPage({ viewport:{width:1440,height:1000},permissions:['camera'] });
const errors=[],checks=[],requests=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>{if (/\/api\/(build|observe)$/.test(request.url())) requests.push({path:new URL(request.url()).pathname,body:request.postDataJSON()});});
const idle = () => page.waitForFunction(()=>!document.getElementById('build').disabled);
const ready = number => page.waitForFunction(n=>document.getElementById('version-label').textContent===`VERSION ${String(n).padStart(2,'0')}`,number);
try {
  await mkdir('.artifacts',{recursive:true});
  await page.goto(base); await idle();
  assert.ok((await page.locator('#build').boundingBox()).y<1000);
  await page.locator('#try-demo').click(); await ready(1);
  const frame=page.frameLocator('#preview');
  await frame.getByRole('textbox',{name:'Task title',exact:true}).fill('Review onboarding');
  await frame.getByRole('button',{name:'Add task',exact:true}).click();
  await frame.getByRole('combobox',{name:'Move Review onboarding',exact:true}).selectOption('done');
  assert.match(await frame.locator('#done').innerText(),/Review onboarding/);
  await frame.getByRole('searchbox',{name:'Search tasks'}).fill('no-match');
  assert.equal(await frame.locator('.task').count(),0);
  await frame.getByRole('searchbox',{name:'Search tasks'}).fill('');
  assert.equal(requests.length,0); checks.push('example add, move, search with zero model requests; build visible above fold');
  await page.screenshot({path:'.artifacts/onboarding-desktop.png',fullPage:true});
  await page.locator('#new-session').click();await page.locator('#confirm-reset').click();
  await page.locator('#example').click(); await page.locator('#build').click();
  await page.locator('#decline-consent').click();assert.equal(requests.length,0);
  await page.locator('#build').click();await page.locator('#accept-consent').click();await ready(1);await idle();
  assert.deepEqual(requests.map(r=>r.path),['/api/build']);
  assert.ok(requests[0].body.image);assert.equal(await page.locator('#include-frame').isChecked(),false);
  checks.push('consent gates sharing; visual build uses one turn; frame remains visible');
  await page.locator('#direction').fill('Make the heading smaller');await page.locator('#build').click();await ready(2);await idle();
  assert.equal(requests[1].body.image,null);assert.ok(requests[1].body.previous);
  assert.ok(await page.locator('#reference').isVisible());checks.push('typed revision sends no old image and retains evidence');
  await page.route('**/api/preview',route=>route.fulfill({status:503,json:{error:'Preview temporarily unavailable'}}));
  await page.locator('#direction').fill('Change the spacing');await page.locator('#build').click();
  await page.waitForFunction(()=>document.querySelectorAll('.revision').length===3&&!document.getElementById('build').disabled);
  assert.equal(await page.locator('#download').isDisabled(),false);assert.ok(await page.locator('#retry-preview').isVisible());
  await page.reload();await idle();assert.equal(await page.locator('.revision').count(),3);
  await page.unroute('**/api/preview');await page.locator('#retry-preview').click();await ready(3);
  assert.equal(requests.length,3);checks.push('preview failure retains source across reload; retry uses zero model calls');
  await page.route('**/api/session',route=>route.fulfill({status:503,json:{error:'Status unavailable'}}));
  await page.reload();await page.locator('#error:not([hidden])').waitFor();
  assert.equal(await page.locator('.revision').count(),3);assert.equal(await page.locator('#source').isDisabled(),false);
  await page.locator('#source').click();assert.match(await page.locator('#source-code').innerText(),/DAYLIGHT/);await page.getByRole('button',{name:'Close source',exact:true}).click();
  const download=page.waitForEvent('download');await page.locator('#download').click();assert.match((await download).suggestedFilename(),/\.html$/);
  checks.push('failed subscription status preserves history, source, and download');
  await page.unroute('**/api/session');
  await page.route('**/api/session',route=>route.fulfill({json:{configured:false,cli:true,token:'mock',remaining:12,reason:'Sign in with ChatGPT.'}}));
  await page.reload();await page.locator('#login:not([hidden])').waitFor();
  assert.equal(await page.locator('#build').isDisabled(),true);assert.equal(await page.locator('#recheck').isEnabled(),true);
  await page.route('**/api/login',route=>route.fulfill({json:{configured:true}}));
  await page.unroute('**/api/session');await page.locator('#login').click();await idle();
  checks.push('missing login offers explicit sign-in and recheck; sign-in action recovers');
  await page.locator('#connect').click();await page.getByText('LIVE · LOCAL ONLY',{exact:true}).waitFor();
  assert.ok(await page.locator('#include-frame').isChecked());
  await page.locator('#camera-off').click();
  assert.equal(await page.locator('#camera').evaluate(v=>v.srcObject),null);checks.push('synthetic camera starts locally and stops');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.ok(await page.locator('#activity').isVisible());checks.push('mobile no overflow and elapsed status remains available');
  await page.screenshot({path:'.artifacts/onboarding-mobile.png',fullPage:true});
  let release;
  const pending=new Promise(resolve=>{release=resolve;});
  await page.route('**/api/build',async route=>{await pending;await route.fulfill({json:{result:{title:'Canceled result',html,reply:'',changes:[]}}}).catch(()=>{});});
  await page.locator('#direction').fill('A canceled change');await page.locator('#build').click();
  await page.locator('#accept-consent').click();await page.locator('#cancel').click();release();await idle();
  assert.equal(await page.locator('.revision').count(),3);checks.push('canceled generation is not accepted');
  assert.deepEqual(errors,[]);
  await writeFile('.artifacts/recovery-report.json',JSON.stringify({checks,errors},null,2));
  console.log(`PASS: ${checks.length} recovery browser checks; ${errors.length} page errors.`);
  for(const check of checks)console.log(`- ${check}`);
} finally { await browser.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve)); }
